func TestDownlinkNASTransportMarshalBinary(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name     string
		input    *DownlinkNASTransport
		expected []byte
	}{
		{
			name: "Case 1",
			input: &DownlinkNASTransport{
				AMFUENGAPID: &ie.AMFUENGAPID{
					Value: 1,
				},
				RANUENGAPID: &ie.RANUENGAPID{
					Value: 3456106496,
				},
				NASPDU: &ie.NASPDU{
					Value: aper.OctetString([]byte{
						0x7e, 0x00, 0x56, 0x00, 0x02, 0x00,
						0x00, 0x21, 0x0b, 0x27, 0xbc, 0xa2, 0xd9, 0xf5, 0xee, 0x4e, 0xba, 0xe5,
						0xdf, 0xeb, 0xfe, 0xc2, 0x1f, 0xf5, 0x20, 0x10, 0x61, 0x52, 0x7a, 0x22,
						0xc3, 0x40, 0x80, 0x00, 0xaf, 0x28, 0x91, 0x7f, 0x7c, 0x53, 0x82, 0xf8,
					}),
				},
			},
			expected: []byte{
				0x00, 0x04, 0x40, 0x41, 0x00, 0x00, 0x03, 0x00, 0x0a,
				0x00, 0x02, 0x00, 0x01, 0x00, 0x55, 0x00, 0x05, 0xc0, 0xce, 0x00, 0x00,
				0x00, 0x00, 0x26, 0x00, 0x2b, 0x2a, 0x7e, 0x00, 0x56, 0x00, 0x02, 0x00,
				0x00, 0x21, 0x0b, 0x27, 0xbc, 0xa2, 0xd9, 0xf5, 0xee, 0x4e, 0xba, 0xe5,
				0xdf, 0xeb, 0xfe, 0xc2, 0x1f, 0xf5, 0x20, 0x10, 0x61, 0x52, 0x7a, 0x22,
				0xc3, 0x40, 0x80, 0x00, 0xaf, 0x28, 0x91, 0x7f, 0x7c, 0x53, 0x82, 0xf8,
			},
		},
	}

	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			b, err := tc.input.MarshalBinary()
			if tc.expected != nil {
				require.NoError(t, err)
				require.Equal(t, tc.expected, b)
			} else {
				require.Error(t, err)
			}
		})
	}
}

